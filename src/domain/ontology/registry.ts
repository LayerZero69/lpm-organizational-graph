const CONTRACTS_BY_TYPE = new Map<EdgeType, RelationshipContract>(
  RELATIONSHIP_CONTRACTS.map((contract) => [contract.edgeType, contract]),
)

export function relationshipContract(edgeType: EdgeType): RelationshipContract {
  const contract = CONTRACTS_BY_TYPE.get(edgeType)
  if (!contract) throw new Error(`No relationship contract registered for edge type ${edgeType}`)
  return contract
}

/** Every declared edge type has exactly one contract, and vice versa. */
export function edgeTypesWithoutContract(): EdgeType[] {
  return EDGE_TYPES.filter((edgeType) => !CONTRACTS_BY_TYPE.has(edgeType))
}

/** Edge types with at least one source type whose relationship Lapemo owns. */
export function projectedEdgeTypes(): EdgeType[] {
  return RELATIONSHIP_CONTRACTS.filter(
    (c) => c.lapemoSourceOfTruth !== null && Object.keys(c.lapemoSourceOfTruth).length > 0,
  ).map((c) => c.edgeType)
}

/** Edge types with no Lapemo owner for any source type, canonical in this graph. */
export function graphCanonicalEdgeTypes(): EdgeType[] {
  return RELATIONSHIP_CONTRACTS.filter(
    (c) => c.lapemoSourceOfTruth === null || Object.keys(c.lapemoSourceOfTruth).length === 0,
  ).map((c) => c.edgeType)
}

/** Resolve the owning Lapemo record for one concrete source type, or null. */
export function lapemoOwnerFor(edgeType: EdgeType, fromNodeType: NodeType): string | null {
  return relationshipContract(edgeType).lapemoSourceOfTruth?.[fromNodeType] ?? null
}
