/**
 * The machine-readable ontology registry.
 *
 * This is the contract `validate:ontology` enforces. Every edge type declares
 * its allowed node pairs, its single canonical direction, cardinality, temporal
 * overlap rule, evidence and confidence requirements, and the Lapemo record that
 * owns the relationship when one exists.
 *
 * `lapemoSourceOfTruth` is the load-bearing field. When it is set, the edge is a
 * DERIVED PROJECTION: Lapemo owns the writable truth and this package must never
 * treat the edge as authoritative to write back. When it is null, the edge is
 * canonical in the graph because no other system models the relationship at all.
 */

